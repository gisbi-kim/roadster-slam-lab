import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const base=process.argv[2]||'http://127.0.0.1:5173';
await page.goto(base,{waitUntil:'networkidle'});
await page.waitForFunction(()=>window.__reconstruction?.ready,{timeout:60000});
const stats=await page.evaluate(()=>window.__reconstruction);
assert(stats.pointCount>1000);assert(stats.frameCount>10);
await page.locator('#scrub').fill('30');
await page.locator('#scrub').dispatchEvent('input');
await page.waitForFunction(()=>document.querySelector('#frame').complete);
assert.match(await page.locator('#frame-label').innerText(),/^31 /);
await page.locator('#mode').selectOption('frame');
await page.locator('#mode').selectOption('cumulative');
await page.locator('#mode').selectOption('all');
await page.locator('#follow').click();await page.locator('#reset').click();
await page.locator('#play').click();
await page.waitForTimeout(500);
await page.locator('#play').click();
assert.notEqual(await page.locator('#scrub').inputValue(),'30');
await page.locator('#scrub').fill('20');await page.locator('#scrub').dispatchEvent('input');
await page.waitForTimeout(500);
await page.screenshot({path:'runtime/viewer-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(300);
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.screenshot({path:'runtime/viewer-mobile.png',fullPage:true});
assert.deepEqual(errors,[]);
console.log(JSON.stringify({base,...stats,errors,interactionChecks:'passed',mobileOverflow:false}));
await browser.close();
